/**
 * Resonance Stories — Service Worker
 * Cache-first for story assets, network-first for app shell updates.
 */

const CACHE_NAME = 'resonance-stories-v8';
const APP_SHELL = [
  './',
  './index.html',
  './styles.css',
  './audio-engine.js',
  './story-player.js',
  './manifest.json',
  './icon.svg'
];

// Install: cache the app shell
self.addEventListener('install', event => {
  event.waitUntil(
    caches.open(CACHE_NAME)
      .then(cache => cache.addAll(APP_SHELL))
      .then(() => self.skipWaiting())
  );
});

// Activate: clean old caches
self.addEventListener('activate', event => {
  event.waitUntil(
    caches.keys().then(keys =>
      Promise.all(
        keys.filter(k => k !== CACHE_NAME).map(k => caches.delete(k))
      )
    ).then(() => self.clients.claim())
  );
});

// Fetch: cache-first for stories, network-first for app shell
self.addEventListener('fetch', event => {
  const url = new URL(event.request.url);

  // Story assets (JSON, audio files) — cache-first
  if (url.pathname.includes('/stories/')) {
    event.respondWith(
      caches.match(event.request).then(cached => {
        if (cached) return cached;
        return fetch(event.request).then(response => {
          if (response.ok) {
            const clone = response.clone();
            caches.open(CACHE_NAME).then(cache => cache.put(event.request, clone));
          }
          return response;
        });
      })
    );
    return;
  }

  // App shell — network-first with cache fallback
  event.respondWith(
    fetch(event.request)
      .then(response => {
        if (response.ok) {
          const clone = response.clone();
          caches.open(CACHE_NAME).then(cache => cache.put(event.request, clone));
        }
        return response;
      })
      .catch(() => caches.match(event.request))
  );
});
